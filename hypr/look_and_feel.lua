---@module 'hl'

-- Design / look and feel

hl.config({
    animations = {
        enabled = true
    }
})

-- Fades only (plus the border colour). Windows never scale or move (apps redraw late during that, which felt nauseating)
-- and workspaces switch instantly; a short fade doesn't depend on the app keeping up.
-- speed is in tenths of a second (1 = 100 ms). Layers (the quickshell bar, menus and overlays)
-- aren't animated here; quickshell does its own small fade (MenuStyle.anim*).
-- Too much still? Set animations.enabled above to false.
hl.curve("snap", { type = "bezier", points = { {0.2, 0.9}, {0.3, 1} } })
hl.animation({ leaf = "global",     enabled = true,  speed = 1,   bezier = "snap" })
hl.animation({ leaf = "windows",    enabled = false })
hl.animation({ leaf = "workspaces", enabled = false })
hl.animation({ leaf = "layers",     enabled = false })
hl.animation({ leaf = "fadeLayersIn",  enabled = false })
hl.animation({ leaf = "fadeLayersOut", enabled = false })
hl.animation({ leaf = "border",     enabled = true,  speed = 1.5, bezier = "snap" })

-- Border colours come from theme_colors.lua (generated by quickshell/theme/apply.py from
-- quickshell/theme/themes.json). Cherry is the fallback if that file is missing or broken.
local ok, themeColors = pcall(require, "theme_colors")
if not ok or type(themeColors) ~= "table" then
    themeColors = { active_border = "rgb(c7a4cc)", inactive_border = "rgb(20091d)" }
end

hl.config({
    general = {
        gaps_in = 5,
        gaps_out = 10,
        border_size = 1,
        resize_on_border = true,
        layout = "dwindle",
        allow_tearing = false,

        col = {
            active_border = themeColors.active_border, -- theme shadow (focused, so also the window under the mouse)
            inactive_border = themeColors.inactive_border -- theme outline
        }
    }
})

hl.config({
    decoration = {
        rounding = 0,
        active_opacity = 1.0,
        inactive_opacity = 1.0,

        blur = {
            enabled = false
        }
    }
})

hl.config({
    misc = {
        force_default_wallpaper = 0,
        disable_hyprland_logo = true,
        -- Let an app raise and focus its own window when asked (clicking a notification
        -- opens the Discord chat in Vesktop, even from the spotifyspace scratchpad)
        focus_on_activate = true
    }
})
